#!/usr/bin/env python3
"""
CPython runtime differential harness.

Validates that pyrift rules agree with empirically observed
runtime behaviour differences across CPython versions.

Each entry maps a rule to:
- which runtime probe confirms it,
- what the expected transition is,
- which versions are affected,
- which versions are explicitly not affected.

Run:
    python benchmark/runtime_harness.py

Requires runtime probe JSON files in compatibility-benchmark/.
Generated by:
    python compatibility-benchmark/cpython_runtime_probe.py

Honesty contract (2026-09 review, point 5)
-------------------------------------------
Earlier versions of this harness printed "All rules verified against
runtime probe data" even when most required probe files were missing
and most rules were never checked at all. That is a credibility
problem, not a convenience: a rule with no runtime evidence must never
be reported the same way as one that has been.

This harness now reports three explicit states per rule, matching
``pyrift.finding.RuntimeVerificationState``:

    VERIFIED            every required probe file was present and every
                         check passed.
    PARTIALLY_VERIFIED  at least one required probe was present and
                         passed, but at least one required probe file
                         was missing.
    UNVERIFIED          no required probe file was available at all.

Only rules in ``VERIFIED_RULES`` are runtime-checked by this harness at
all -- currently a small, deliberately curated subset of the 118-rule
catalog (see ``pyrift.rule_metadata.FULLY_RUNTIME_VERIFIED_RULES``,
which must stay in sync with the "VERIFIED"-eligible entries here; a
test enforces this). Every other rule's ``runtime_verification`` field
is ``NOT_APPLICABLE`` -- meaning "this rule's claim was never intended
to be checked by executing code" -- rather than silently defaulting to
something that looks like a pass. The final summary line always states
how many of the 118 rules were actually checked, so this can't be
misread as blanket coverage.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).parent.parent
PROBE_DIR = ROOT / "compatibility-benchmark"

sys.path.insert(0, str(ROOT))

# Runtime-verified rule evidence.
#
# Each entry contains:
#   probe_key:
#       Key in the runtime probe JSON.
#   description:
#       Human-readable explanation of the evidence.
#   versions_affected:
#       Versions where the rule's runtime behaviour is expected.
#   versions_not_affected:
#       Versions where the rule's runtime behaviour is explicitly
#       expected NOT to occur.
#   verify:
#       Predicate validating the affected-version observation.
#   verify_not:
#       Predicate validating the non-affected-version observation.
VERIFIED_RULES: dict[str, dict[str, Any]] = {
    "CPY022": {
        "probe_key": "bool_inversion",
        "description": (
            "bitwise inversion on bool emits DeprecationWarning "
            "(Python 3.12+)"
        ),
        "versions_affected": ["3.12", "3.13", "3.14"],
        "verify": lambda v: (
            isinstance(v, list)
            and "DeprecationWarning" in v
        ),
    },
    "CPY027": {
        "probe_key": "locale_resetlocale",
        "description": "locale.resetlocale() raises AttributeError",
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: (
            isinstance(v, str) and "AttributeError" in v
        ),
    },
    "CPY029": {
        "probe_key": "locals_mutation",
        "description": "locals() mutation returns 0 (no effect)",
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: v == 0,
    },
    "CPY036": {
        "probe_key": "datetime_utcnow",
        "description": "datetime.utcnow() raises DeprecationWarning",
        "versions_affected": ["3.12", "3.13", "3.14"],
        "verify": lambda v: (
            isinstance(v, dict)
            and "DeprecationWarning" in v.get("warnings", [])
        ),
    },
    "CPY038": {
        "probe_key": "asyncio_get_event_loop",
        "description": (
            "asyncio.get_event_loop() without a running loop "
            "warns in Python 3.12-3.13 and raises RuntimeError "
            "in Python 3.14"
        ),
        "versions_affected": ["3.12", "3.13", "3.14"],
        "verify_by_version": {
            "3.12": lambda v: (
                isinstance(v, dict)
                and v.get("raised") is None
                and "DeprecationWarning" in v.get("warnings", [])
            ),
            "3.13": lambda v: (
                isinstance(v, dict)
                and v.get("raised") is None
                and "DeprecationWarning" in v.get("warnings", [])
            ),
            "3.14": lambda v: (
                isinstance(v, dict)
                and v.get("raised") == "RuntimeError"
                and not v.get("warnings", [])
            ),
        },
    },
    "CPY050": {
        "probe_key": "purepath_is_reserved",
        "description": (
            "PurePath.is_reserved() is deprecated "
            "(always False on non-Windows)"
        ),
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: v is False,
    },
    "CPY057": {
        "probe_key": "pickle_default_protocol",
        "description": "pickle default protocol is 5 (changed in 3.14)",
        "versions_affected": ["3.14", "3.15"],
        "versions_not_affected": ["3.13"],
        "verify": lambda v: v == 5,
        "verify_not": lambda v: v == 4,
    },
}


def load_probe(version: str) -> dict[str, Any] | None:
    """Load a runtime probe JSON file for a Python version."""
    path = PROBE_DIR / f"runtime-{version}.json"

    if not path.exists():
        return None

    try:
        value = json.loads(
            path.read_text(encoding="utf-8-sig")
        )
    except (OSError, UnicodeError, json.JSONDecodeError):
        return None

    if not isinstance(value, dict):
        return None

    return value


def main() -> int:
    print("CPython Runtime Differential Harness")
    print("=" * 50)

    try:
        from pyrift.rule_metadata import FULLY_RUNTIME_VERIFIED_RULES
        from pyrift.scanner import ALL_RULES

        total_rule_count = len(ALL_RULES)
    except ImportError:  # pragma: no cover
        FULLY_RUNTIME_VERIFIED_RULES = set(VERIFIED_RULES)
        total_rule_count = None

    failed = False
    versions = [
        "3.10",
        "3.11",
        "3.12",
        "3.13",
        "3.14",
        "3.15",
    ]

    probes: dict[str, dict[str, Any]] = {}

    for version in versions:
        probe = load_probe(version)

        if probe is not None:
            probes[version] = probe

    if not probes:
        print(
            "[WARN] No runtime probe files found "
            "in compatibility-benchmark/"
        )
        print(
            "       Run: "
            "python compatibility-benchmark/"
            "cpython_runtime_probe.py"
        )
        print(
            "[UNVERIFIED] Harness could not run -- no probe data "
            f"available. 0 of {len(VERIFIED_RULES)} registered rules "
            "were checked; this is NOT the same as those rules being "
            "verified."
        )
        # Exit non-zero: unlike the old behaviour, "no probe data" is
        # not silently treated as success. CI should surface this.
        return 1

    versions_found = list(probes)

    print(
        "Probe data available for: "
        f"{', '.join(versions_found)}"
    )
    print()

    verified_count = 0
    partial_count = 0
    unverified_count = 0

    for rule_id, entry in sorted(VERIFIED_RULES.items()):
        key = entry["probe_key"]
        desc = entry["description"]
        affected = set(entry["versions_affected"])
        not_affected = set(
            entry.get("versions_not_affected", [])
        )
        verify_fn = entry.get("verify")
        verify_by_version = entry.get("verify_by_version")
        verify_not_fn = entry.get("verify_not")

        rule_ok = True
        skipped = False

        required_versions = affected | not_affected

        for version in sorted(required_versions):
            probe = probes.get(version)

            if probe is None:
                print(
                    f"    [MISSING PROBE] v{version}: "
                    "required runtime probe is not available -- "
                    f"{rule_id} is NOT verified for this version"
                )
                skipped = True
                continue

            if key not in probe:
                print(
                    f"    [MISSING PROBE] v{version}: "
                    f"probe key '{key}' is missing -- "
                    f"{rule_id} is NOT verified for this version"
                )
                skipped = True
                continue

            value = probe[key]

            if version in affected:
                if verify_by_version is not None:
                    version_verify = verify_by_version.get(version)

                    if version_verify is None:
                        print(
                            f"    [FAIL] v{version}: no verifier is defined "
                            f"for {rule_id}"
                        )
                        rule_ok = False
                        failed = True
                        continue

                    if not version_verify(value):
                        print(
                            f"    [FAIL] v{version}: expected "
                            f"'{desc}' but got {value!r}"
                        )
                        rule_ok = False
                        failed = True

                elif verify_fn is not None and not verify_fn(value):
                    print(
                        f"    [FAIL] v{version}: expected "
                        f"'{desc}' but got {value!r}"
                    )
                    rule_ok = False
                    failed = True

                elif verify_fn is None:
                    print(
                        f"    [FAIL] v{version}: no affected-version "
                        f"verifier is defined for {rule_id}"
                    )
                    rule_ok = False
                    failed = True

            elif version in not_affected:
                if verify_not_fn is None:
                    print(
                        f"    [FAIL] v{version}: "
                        "no non-affected-version verifier "
                        f"is defined for {rule_id}"
                    )
                    rule_ok = False
                    failed = True
                    continue

                if not verify_not_fn(value):
                    print(
                        f"    [FAIL] v{version}: expected "
                        f"non-affected behaviour for '{desc}' "
                        f"but got {value!r}"
                    )
                    rule_ok = False
                    failed = True

        if not rule_ok:
            status = "[FAIL]"
        elif skipped:
            status = "[PARTIALLY_VERIFIED]"
            partial_count += 1
        else:
            status = "[VERIFIED]"
            verified_count += 1

        print(f"  {status} {rule_id}: {desc}")

    unverified_count = len(VERIFIED_RULES) - verified_count - partial_count

    print()

    # Cross-check against pyrift.rule_metadata.FULLY_RUNTIME_VERIFIED_RULES:
    # a rule may only claim RuntimeVerificationState.VERIFIED in the
    # metadata registry if this harness actually verified it end-to-end
    # (every required version present and passing) on this run.
    fully_verified_here = {
        rule_id
        for rule_id, entry in sorted(VERIFIED_RULES.items())
        if rule_id not in _last_run_failures_or_partial(
            VERIFIED_RULES, probes
        )
    }
    claimed_but_not_verified = FULLY_RUNTIME_VERIFIED_RULES - fully_verified_here
    if claimed_but_not_verified:
        print(
            "[FAIL] pyrift.rule_metadata.FULLY_RUNTIME_VERIFIED_RULES "
            "claims VERIFIED for rules this run could not fully verify: "
            f"{sorted(claimed_but_not_verified)}"
        )
        failed = True

    if failed:
        print(
            "[FAIL] Runtime harness failed -- "
            "rule evidence mismatch detected."
        )
        return 1

    total_desc = (
        f"{total_rule_count} rules in the full catalog"
        if total_rule_count is not None
        else "the full rule catalog"
    )
    print(
        f"Checked {len(VERIFIED_RULES)} rules out of {total_desc}: "
        f"{verified_count} VERIFIED, {partial_count} PARTIALLY_VERIFIED, "
        f"{unverified_count} UNVERIFIED (missing probe data)."
    )
    print(
        "All other rules in the catalog have runtime_verification="
        "NOT_APPLICABLE and make no runtime-checked claim at all -- "
        "this harness intentionally does not claim broader coverage "
        "than it has."
    )
    return 0


def _last_run_failures_or_partial(
    verified_rules: dict[str, dict[str, Any]],
    probes: dict[str, dict[str, Any]],
) -> set[str]:
    """Recompute which rules were NOT fully verified on this run (no
    missing probes, no failing checks), for the metadata cross-check
    above. Kept as a pure function so it can be unit tested directly."""
    incomplete: set[str] = set()

    for rule_id, entry in verified_rules.items():
        affected = set(entry["versions_affected"])
        not_affected = set(entry.get("versions_not_affected", []))
        required_versions = affected | not_affected
        key = entry["probe_key"]

        for version in required_versions:
            probe = probes.get(version)
            if probe is None or key not in probe:
                incomplete.add(rule_id)
                break

    return incomplete


if __name__ == "__main__":
    sys.exit(main())