#!/usr/bin/env python3
"""
CPython runtime differential harness.

Validates that pyrift rules agree with empirically observed
runtime behaviour differences across CPython versions.

Each entry maps a rule to: which runtime probe confirms it,
what the expected transition is, and on which versions.

Run: python benchmark/runtime_harness.py

Requires runtime probe JSON files in compatibility-benchmark/
Generated by: python compatibility-benchmark/cpython_runtime_probe.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
PROBE_DIR = ROOT / "compatibility-benchmark"

# Runtime-verified rule evidence
# Each entry: rule_id -> {probe_key, versions_affected, description}
VERIFIED_RULES = {
    "CPY036": {
        "probe_key": "datetime_utcnow",
        "description": "datetime.utcnow() raises DeprecationWarning",
        "versions_affected": ["3.12", "3.13", "3.14"],
        "verify": lambda v: (
            isinstance(v, dict)
            and "DeprecationWarning" in v.get("warnings", [])
        ),
    },
    "CPY027": {
        "probe_key": "locale_resetlocale",
        "description": "locale.resetlocale() raises AttributeError",
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: isinstance(v, str) and "AttributeError" in v,
    },
    "CPY057": {
        "probe_key": "pickle_default_protocol",
        "description": "pickle default protocol is 5 (changed in 3.14)",
        "versions_affected": ["3.14", "3.15"],
        "verify": lambda v: v == 5,
        "versions_not_affected": ["3.13"],
        "verify_not": lambda v: v == 4,
    },
    "CPY050": {
        "probe_key": "purepath_is_reserved",
        "description": "PurePath.is_reserved() deprecated (always False on non-Windows)",
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: v is False,
    },
    "CPY029": {
        "probe_key": "locals_mutation",
        "description": "locals() mutation returns 0 (no effect)",
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: v == 0,
    },
}


def load_probe(version: str) -> dict | None:
    path = PROBE_DIR / f"runtime-{version}.json"
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except Exception:
        return None


def main() -> int:
    print("CPython Runtime Differential Harness")
    print("=" * 50)

    failed = False
    versions_found = []

    for version in ["3.10", "3.11", "3.12", "3.13", "3.14", "3.15"]:
        probe = load_probe(version)
        if probe:
            versions_found.append(version)

    if not versions_found:
        print("[WARN] No runtime probe files found in compatibility-benchmark/")
        print("       Run: python compatibility-benchmark/cpython_runtime_probe.py")
        print("[OK] Harness skipped (no probe data available)")
        return 0

    print(f"Probe data available for: {', '.join(versions_found)}")
    print()

    for rule_id, entry in sorted(VERIFIED_RULES.items()):
        key = entry["probe_key"]
        desc = entry["description"]
        affected = entry["versions_affected"]
        verify_fn = entry["verify"]

        rule_ok = True
        results = []

        for version in versions_found:
            probe = load_probe(version)
            if key not in probe:
                continue

            value = probe[key]
            is_affected = version in affected
            observed = verify_fn(value)

            if is_affected and not observed:
                results.append(
                    f"    [FAIL] v{version}: expected '{desc}' "
                    f"but got {value!r}"
                )
                rule_ok = False
                failed = True
            elif not is_affected and observed:
                # Check if it should NOT be present on this version
                not_fn = entry.get("verify_not")
                if not_fn and not not_fn(value):
                    results.append(
                        f"    [FAIL] v{version}: should NOT show '{desc}' "
                        f"but got {value!r}"
                    )
                    rule_ok = False
                    failed = True

        status = "[OK]" if rule_ok else "[FAIL]"
        print(f"  {status} {rule_id}: {desc}")
        for r in results:
            print(r)

    print()
    if failed:
        print("[FAIL] Runtime harness failed -- rule evidence mismatch detected.")
        return 1

    print("[OK] All rules verified against runtime probe data.")
    print(f"     {len(VERIFIED_RULES)} rules verified across "
          f"{len(versions_found)} Python versions.")
    return 0


if __name__ == "__main__":
    sys.exit(main())