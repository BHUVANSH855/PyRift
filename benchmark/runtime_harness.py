#!/usr/bin/env python3
"""
CPython runtime differential harness.

Validates that pyrift rules agree with empirically observed
runtime behaviour differences across CPython versions.

Each entry maps a rule to:
- which runtime probe confirms it,
- what the expected transition is,
- which versions are affected,
- which versions are explicitly not affected.

Run:
    python benchmark/runtime_harness.py

Requires runtime probe JSON files in compatibility-benchmark/.
Generated by:
    python compatibility-benchmark/cpython_runtime_probe.py
"""
from __future__ import annotations

import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).parent.parent
PROBE_DIR = ROOT / "compatibility-benchmark"

# Runtime-verified rule evidence.
#
# Each entry contains:
#   probe_key:
#       Key in the runtime probe JSON.
#   description:
#       Human-readable explanation of the evidence.
#   versions_affected:
#       Versions where the rule's runtime behaviour is expected.
#   versions_not_affected:
#       Versions where the rule's runtime behaviour is explicitly
#       expected NOT to occur.
#   verify:
#       Predicate validating the affected-version observation.
#   verify_not:
#       Predicate validating the non-affected-version observation.
VERIFIED_RULES: dict[str, dict[str, Any]] = {
    "CPY036": {
        "probe_key": "datetime_utcnow",
        "description": "datetime.utcnow() raises DeprecationWarning",
        "versions_affected": ["3.12", "3.13", "3.14"],
        "verify": lambda v: (
            isinstance(v, dict)
            and "DeprecationWarning" in v.get("warnings", [])
        ),
    },
    "CPY027": {
        "probe_key": "locale_resetlocale",
        "description": "locale.resetlocale() raises AttributeError",
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: (
            isinstance(v, str) and "AttributeError" in v
        ),
    },
    "CPY057": {
        "probe_key": "pickle_default_protocol",
        "description": "pickle default protocol is 5 (changed in 3.14)",
        "versions_affected": ["3.14", "3.15"],
        "versions_not_affected": ["3.13"],
        "verify": lambda v: v == 5,
        "verify_not": lambda v: v == 4,
    },
    "CPY050": {
        "probe_key": "purepath_is_reserved",
        "description": (
            "PurePath.is_reserved() is deprecated "
            "(always False on non-Windows)"
        ),
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: v is False,
    },
    "CPY029": {
        "probe_key": "locals_mutation",
        "description": "locals() mutation returns 0 (no effect)",
        "versions_affected": ["3.13", "3.14"],
        "verify": lambda v: v == 0,
    },
}


def load_probe(version: str) -> dict[str, Any] | None:
    """Load a runtime probe JSON file for a Python version."""
    path = PROBE_DIR / f"runtime-{version}.json"

    if not path.exists():
        return None

    try:
        value = json.loads(
            path.read_text(encoding="utf-8-sig")
        )
    except (OSError, UnicodeError, json.JSONDecodeError):
        return None

    if not isinstance(value, dict):
        return None

    return value


def main() -> int:
    print("CPython Runtime Differential Harness")
    print("=" * 50)

    failed = False
    versions = [
        "3.10",
        "3.11",
        "3.12",
        "3.13",
        "3.14",
        "3.15",
    ]

    probes: dict[str, dict[str, Any]] = {}

    for version in versions:
        probe = load_probe(version)

        if probe is not None:
            probes[version] = probe

    if not probes:
        print(
            "[WARN] No runtime probe files found "
            "in compatibility-benchmark/"
        )
        print(
            "       Run: "
            "python compatibility-benchmark/"
            "cpython_runtime_probe.py"
        )
        print("[OK] Harness skipped (no probe data available)")
        return 0

    versions_found = list(probes)

    print(
        "Probe data available for: "
        f"{', '.join(versions_found)}"
    )
    print()

    for rule_id, entry in sorted(VERIFIED_RULES.items()):
        key = entry["probe_key"]
        desc = entry["description"]
        affected = set(entry["versions_affected"])
        not_affected = set(
            entry.get("versions_not_affected", [])
        )
        verify_fn: Callable[[Any], bool] = entry["verify"]
        verify_not_fn = entry.get("verify_not")

        rule_ok = True

        required_versions = affected | not_affected

        for version in sorted(required_versions):
            probe = probes.get(version)

            if probe is None:
                # A rule cannot be runtime-verified if the probe
                # for a required version is unavailable.
                print(
                    f"    [FAIL] v{version}: "
                    "required runtime probe is missing"
                )
                rule_ok = False
                failed = True
                continue

            if key not in probe:
                print(
                    f"    [FAIL] v{version}: "
                    f"probe key '{key}' is missing"
                )
                rule_ok = False
                failed = True
                continue

            value = probe[key]

            if version in affected:
                if not verify_fn(value):
                    print(
                        f"    [FAIL] v{version}: expected "
                        f"'{desc}' but got {value!r}"
                    )
                    rule_ok = False
                    failed = True

            elif version in not_affected:
                if verify_not_fn is None:
                    print(
                        f"    [FAIL] v{version}: "
                        "no non-affected-version verifier "
                        f"is defined for {rule_id}"
                    )
                    rule_ok = False
                    failed = True
                    continue

                if not verify_not_fn(value):
                    print(
                        f"    [FAIL] v{version}: expected "
                        f"non-affected behaviour for '{desc}' "
                        f"but got {value!r}"
                    )
                    rule_ok = False
                    failed = True

        status = "[OK]" if rule_ok else "[FAIL]"
        print(f"  {status} {rule_id}: {desc}")

    print()

    if failed:
        print(
            "[FAIL] Runtime harness failed -- "
            "rule evidence mismatch detected."
        )
        return 1

    print(
        "[OK] All rules verified against runtime probe data."
    )
    print(
        f"     {len(VERIFIED_RULES)} rules verified across "
        f"{len(versions_found)} Python versions."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())